// ویرایش — فقط ادمین اصلی (الگوی محتوای سایت: role + assertMainAdmin)
// هر ذخیره → نسخه + ۱
export const updateTerms = createServerFn({ method: 'POST' })
  .validator(z.object({
    role: roleSchema,
    sections: z.array(z.object({
      title: z.string().min(1, 'عنوان بخش الزامی است'),
      items: z.array(z.string().min(1)).min(1, 'هر بخش حداقل یک بند لازم دارد'),
    })).min(1, 'حداقل یک بخش لازم است'),
  }))
  .handler(async ({ data }) => {
    assertMainAdmin(data.role)
    const { role: _role, ...fields } = data
    T.terms = {
      sections: fields.sections,
      version: T.terms.version + 1,
      updatedAt: new Date(),
    }
    return { success: true, version: T.terms.version }
  })